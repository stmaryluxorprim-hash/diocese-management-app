#!/usr/bin/env node
// One-off migration: shrink the oversized files that are ALREADY in the public
// `photos` / `church-logos` buckets (the upload path compresses new files).
//
// SAFE BY DESIGN
//   • default = DRY RUN: downloads + compresses in memory, prints the saving,
//     writes nothing.
//   • --apply uploads the compressed copy under a NEW path (old file untouched),
//     then writes `photo-url-migration.sql`. Run that SQL in the Supabase SQL
//     editor: it swaps old URL → new URL in every text/json column.
//   • Old files are only deleted with a second explicit run: --delete-old
//     (reads photo-url-migration.json). Do that after checking the app.
//
// Usage (service-role key stays in your shell, never in a file):
//   SUPABASE_URL=https://xxx.supabase.co SUPABASE_SERVICE_ROLE_KEY=... \
//     node scripts/compress-existing-photos.mjs [--apply | --delete-old] [--min-kb=80]
//
// Offline test against a local backup folder (no network):
//   node scripts/compress-existing-photos.mjs --local-dir=/path/to/storage
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const args = Object.fromEntries(process.argv.slice(2).map((a) => {
  const [k, v] = a.replace(/^--/, '').split('=');
  return [k, v ?? true];
}));
const MIN = (Number(args['min-kb']) || 80) * 1024;
const IMMUTABLE = String(60 * 60 * 24 * 365);
// Keep in sync with src/lib/image-compress.ts
const MAX = { servants: 640, persons: 640, 'child-requests': 640, priests: 640, store: 800, classes: 800, services: 800,
  messages: 1280, 'child-messages': 1280, notifications: 1280, occasions: 1280, achievements: 1280, exams: 1280, cards: 1600 };
const targetBytes = (m) => (m <= 640 ? 90e3 : m <= 800 ? 130e3 : m <= 1280 ? 220e3 : 380e3);
const REPORT = 'photo-url-migration.json';
const SQLFILE = 'photo-url-migration.sql';

async function compress(buf, folder) {
  const max = folder === '' ? 512 : (MAX[folder] ?? 1280); // '' = church-logos (flat)
  let out = buf;
  for (const q of [82, 72, 62, 50, 40]) {
    out = await sharp(buf).rotate().resize({ width: max, height: max, fit: 'inside', withoutEnlargement: true }).webp({ quality: q }).toBuffer();
    if (out.length <= targetBytes(max)) break;
  }
  return out.length < buf.length ? out : null;
}
const fmt = (n) => (n / 1e6).toFixed(2) + ' MB';

function sqlFor(pairs) {
  const values = pairs.map(([a, b]) => `    ('${a.replace(/'/g, "''")}', '${b.replace(/'/g, "''")}')`).join(',\n');
  return `-- Generated by scripts/compress-existing-photos.mjs — swaps old photo URLs for the compressed copies.
-- Review, then run once in the Supabase SQL editor. Safe to re-run.
set session_replication_role = replica; -- do not fire triggers / notifications for this bulk rewrite
do $mig$
declare
  m record; c record; n bigint; total bigint := 0;
begin
  for m in select * from (values
${values}
  ) as t(old_url, new_url) loop
    for c in
      select table_name, column_name, data_type
      from information_schema.columns col
      where table_schema = 'public'
        and data_type in ('text', 'character varying', 'jsonb', 'json')
        and is_generated = 'NEVER'
        and (select table_type from information_schema.tables t
             where t.table_schema = col.table_schema and t.table_name = col.table_name) = 'BASE TABLE'
    loop
      if c.data_type in ('jsonb', 'json') then
        execute format('update public.%I set %I = replace(%I::text, $1, $2)::%s where %I::text like $3',
                       c.table_name, c.column_name, c.column_name, c.data_type, c.column_name)
          using m.old_url, m.new_url, '%' || m.old_url || '%';
      else
        execute format('update public.%I set %I = replace(%I, $1, $2) where %I like $3',
                       c.table_name, c.column_name, c.column_name, c.column_name)
          using m.old_url, m.new_url, '%' || m.old_url || '%';
      end if;
      get diagnostics n = row_count;
      total := total + n;
    end loop;
  end loop;
  raise notice 'rows updated: %', total;
end
$mig$;
set session_replication_role = origin;
`;
}

// ---------- offline mode ----------
if (args['local-dir']) {
  const root = args['local-dir'];
  let before = 0, after = 0, n = 0;
  const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
  for (const f of walk(root)) {
    const buf = fs.readFileSync(f);
    const folder = path.relative(root, f).split(path.sep).slice(-2, -1)[0] ?? '';
    before += buf.length;
    const out = buf.length > MIN ? await compress(buf, folder) : null;
    after += out ? out.length : buf.length;
    if (out) n++;
  }
  console.log(`[local] ${n} files compressed · ${fmt(before)} → ${fmt(after)} (−${((1 - after / before) * 100).toFixed(0)} %)`);
  process.exit(0);
}

// ---------- online mode ----------
const URL_ = (process.env.SUPABASE_URL || '').replace(/\/$/, '');
const KEY = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
if (!URL_ || !KEY) { console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (shell env only).'); process.exit(1); }
const H = { apikey: KEY, Authorization: `Bearer ${KEY}` };

async function list(bucket, prefix = '') {
  const out = [];
  for (let offset = 0; ; offset += 100) {
    const r = await fetch(`${URL_}/storage/v1/object/list/${bucket}`, {
      method: 'POST', headers: { ...H, 'content-type': 'application/json' },
      body: JSON.stringify({ prefix, limit: 100, offset, sortBy: { column: 'name', order: 'asc' } }),
    });
    if (!r.ok) throw new Error(`list ${bucket}/${prefix}: ${r.status}`);
    const rows = await r.json();
    for (const o of rows) {
      if (o.id === null) out.push(...await list(bucket, prefix ? `${prefix}/${o.name}` : o.name)); // folder
      else out.push({ name: prefix ? `${prefix}/${o.name}` : o.name, size: o.metadata?.size ?? 0, type: o.metadata?.mimetype ?? '' });
    }
    if (rows.length < 100) break;
  }
  return out;
}
const publicUrl = (bucket, p) => `${URL_}/storage/v1/object/public/${bucket}/${p.split('/').map(encodeURIComponent).join('/')}`;

if (args['delete-old']) {
  const rep = JSON.parse(fs.readFileSync(REPORT, 'utf8'));
  for (const [bucket, oldPath] of rep.map((r) => [r.bucket, r.oldPath])) {
    const r = await fetch(`${URL_}/storage/v1/object/${bucket}/${oldPath}`, { method: 'DELETE', headers: H });
    console.log(r.ok ? 'deleted' : `FAILED ${r.status}`, bucket, oldPath);
  }
  process.exit(0);
}

const APPLY = !!args.apply;
const report = []; let before = 0, after = 0;
for (const bucket of ['photos', 'church-logos']) {
  for (const o of await list(bucket)) {
    if (!/\.(jpe?g|png|webp)$/i.test(o.name) || o.size <= MIN) continue;
    const r = await fetch(publicUrl(bucket, o.name));
    if (!r.ok) { console.warn('skip (download failed)', o.name); continue; }
    const buf = Buffer.from(await r.arrayBuffer());
    const parts = o.name.split('/');
    const folder = bucket === 'church-logos' ? '' : parts[0];
    const out = await compress(buf, folder);
    if (!out) continue;
    const base = parts.pop().replace(/\.[a-zA-Z0-9]+$/, '');
    const newPath = [...parts, `${Date.now()}-${base.replace(/^\d+-/, '')}.webp`].join('/');
    before += buf.length; after += out.length;
    console.log(`${(buf.length / 1e3) | 0} KB → ${(out.length / 1e3) | 0} KB  ${bucket}/${o.name}`);
    if (APPLY) {
      const up = await fetch(`${URL_}/storage/v1/object/${bucket}/${newPath}`, {
        method: 'POST', headers: { ...H, 'content-type': 'image/webp', 'cache-control': `max-age=${IMMUTABLE}`, 'x-upsert': 'false' }, body: out,
      });
      if (!up.ok) { console.error('  upload FAILED', up.status, await up.text()); continue; }
      report.push({ bucket, oldPath: o.name, newPath, oldUrl: publicUrl(bucket, o.name), newUrl: publicUrl(bucket, newPath) });
    }
  }
}
console.log(`\n${APPLY ? 'APPLIED' : 'DRY RUN'}: ${fmt(before)} → ${fmt(after)} (−${before ? ((1 - after / before) * 100).toFixed(0) : 0} %)`);
if (APPLY && report.length) {
  fs.writeFileSync(REPORT, JSON.stringify(report, null, 2));
  fs.writeFileSync(SQLFILE, sqlFor(report.map((r) => [r.oldUrl, r.newUrl])));
  console.log(`Wrote ${REPORT} and ${SQLFILE}. Next: run the SQL in the Supabase SQL editor, check the app, then --delete-old.`);
}
